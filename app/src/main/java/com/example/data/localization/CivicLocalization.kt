    Department.WATER_WORKS -> civicString(CivicStrings.DEPT_WATER)
    Department.POWER_UTILITY -> civicString(CivicStrings.DEPT_POWER)
    Department.DRAINAGE_FLOOD -> civicString(CivicStrings.DEPT_DRAINAGE)
    Department.PUBLIC_WORKS -> civicString(CivicStrings.DEPT_PWD)
}

