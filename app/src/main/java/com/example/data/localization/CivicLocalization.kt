    EN("en", "English", "English", "🇬🇧"),
    HI("hi", "Hindi", "हिन्दी", "🇮🇳"),
    BN("bn", "Bengali", "বাংলা", "🇮🇳"),
    TE("te", "Telugu", "తెలుగు", "🇮🇳"),
    MR("mr", "Marathi", "मराठी", "🇮🇳"),
    TA("ta", "Tamil", "தமிழ்", "🇮🇳"),
    GU("gu", "Gujarati", "ગુજરાતી", "🇮🇳"),
    KN("kn", "Kannada", "ಕನ್ನಡ", "🇮🇳"),
    ML("ml", "Malayalam", "മലയാളം", "🇮🇳"),
    PA("pa", "Punjabi", "ਪੰਜਾਬੀ", "🇮🇳"),
    OR("or", "Odia", "ଓଡ଼ିଆ", "🇮🇳"),
    AS("as", "Assamese", "অসমীয়া", "🇮🇳"),
    UR("ur", "Urdu", "اردو", "🇮🇳");

    companion object {
        fun fromCode(code: String): AppLanguage =
            entries.firstOrNull { it.code.equals(code, ignoreCase = true) } ?: EN
    }
}

val LocalCivicLanguage = staticCompositionLocalOf { AppLanguage.EN }

@Composable
fun civicString(key: String): String {
    val lang = LocalCivicLanguage.current
    return CivicStrings.get(key, lang)
}

@Composable
fun IssueCategory.localizedName(): String = when (this) {
    IssueCategory.ROADS -> civicString(CivicStrings.CAT_ROADS)
    IssueCategory.WATER -> civicString(CivicStrings.CAT_WATER)
    IssueCategory.GARBAGE -> civicString(CivicStrings.CAT_GARBAGE)
    IssueCategory.STREETLIGHT -> civicString(CivicStrings.CAT_STREETLIGHTS)
    IssueCategory.ELECTRICITY -> civicString(CivicStrings.CAT_ELECTRICITY)
    IssueCategory.DRAINAGE -> civicString(CivicStrings.CAT_DRAINAGE)
    IssueCategory.PUBLIC_PROPERTY -> civicString(CivicStrings.CAT_PUBLIC_PROPERTY)
    IssueCategory.OTHER -> civicString(CivicStrings.CAT_OTHER)
}

@Composable
fun IssueStatus.localizedName(): String = when (this) {
    IssueStatus.PENDING -> civicString(CivicStrings.STATUS_PENDING)
    IssueStatus.IN_PROGRESS -> civicString(CivicStrings.STATUS_IN_PROGRESS)
    IssueStatus.RESOLVED -> civicString(CivicStrings.STATUS_RESOLVED)
    IssueStatus.REJECTED -> civicString(CivicStrings.STATUS_REJECTED)
}

@Composable
fun IssuePriority.localizedName(): String = when (this) {
    IssuePriority.LOW -> civicString(CivicStrings.PRIORITY_LOW)
    IssuePriority.MEDIUM -> civicString(CivicStrings.PRIORITY_MEDIUM)
    IssuePriority.HIGH -> civicString(CivicStrings.PRIORITY_HIGH)
}

@Composable
fun Department.localizedName(): String = when (this) {
    Department.UNASSIGNED -> civicString(CivicStrings.DEPT_UNASSIGNED)
    Department.SANITATION -> civicString(CivicStrings.DEPT_SANITATION)
